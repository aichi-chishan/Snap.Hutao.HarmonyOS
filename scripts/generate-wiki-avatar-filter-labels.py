#!/usr/bin/env python3
"""Project character Wiki labels from the bundled, pinned Windows source snapshot."""

import argparse
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "scripts/data/wiki-avatar-labels.json"
TARGET = ROOT / "entry/src/main/ets/service/WikiAvatarFilterVocabulary.ets"
SOURCE = "SnapHutaoRemasteringProject/Snap.Hutao.Remastered"
REVISION = "3b7475ed3eca4aedf9cb81d94741bfbe6fa189f5"
RESOURCE_PATH = "src/Snap.Hutao.Remastered/Snap.Hutao.Remastered/Resource/Localization"
LOCALES = ("zh-Hans", "zh-Hant", "en", "de", "es", "fr", "id", "it", "ja", "ko", "pt", "ru", "th", "tr", "vi")
TERMS = {
    "qualities": {"4": "ItemQualityPurple", "5": "ItemQualityOrange", "105": "ItemQualityRed"},
    "weapons": {"1": "WeaponTypeSwordOneHand", "10": "WeaponTypeCatalyst", "11": "WeaponTypeClaymore",
                "12": "WeaponTypeBow", "13": "WeaponTypePole"},
    "elements": {"火": "ElementNameFire", "水": "ElementNameWater", "草": "ElementNameGrass", "雷": "ElementNameElec",
                 "风": "ElementNameWind", "冰": "ElementNameIce", "岩": "ElementNameRock"},
    "associations": {"1": "AssociationTypeMondstadt", "2": "AssociationTypeLiyue", "4": "AssociationTypeFatui",
                     "5": "AssociationTypeInazuma", "6": "AssociationTypeRanger", "7": "AssociationTypeSumeru",
                     "8": "AssociationTypeFontaine", "9": "AssociationTypeNatlan", "10": "AssociationTypeSnezhnaya",
                     "11": "AssociationTypeOmniScourge", "12": "AssociationTypeNodkrai", "14": "AssociationTypeHVision",
                     "15": "AssociationTypeSnezhnayaStar"},
    "bodies": {"1": "BodyTypeBoy", "2": "BodyTypeGirl", "3": "BodyTypeLady", "4": "BodyTypeMale", "5": "BodyTypeLoli"},
}
GUIDE_KEYS = (
    "ViewPageWiKiAvatarStrategyChineseButtonLabel",
    "ViewPageWiKiAvatarStrategyBilibiliButtonLabel",
    "ViewPageWiKiAvatarStrategyOverseaButtonLabel",
    "ViewModelWikiAvatarStrategyNotFound",
)
KEYS = ["ModelIntrinsic" + suffix for group in TERMS.values() for suffix in group.values()] + list(GUIDE_KEYS)


def read_snapshot():
    snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    if snapshot.get("source") != SOURCE or snapshot.get("revision") != REVISION or snapshot.get("keys") != KEYS:
        raise ValueError("Character Wiki label source or key list does not match the pinned snapshot")
    localized = snapshot.get("locales", {})
    if set(localized) != set(LOCALES):
        raise ValueError("Character Wiki label snapshot must contain all 15 languages")
    for locale, values in localized.items():
        if not isinstance(values, list) or len(values) != len(KEYS) or any(not isinstance(value, str) or not value.strip() for value in values):
            raise ValueError(f"Invalid source labels for {locale}")
    return snapshot


def windows_snapshot(directory):
    def resources(filename):
        content = subprocess.check_output(["git", "-C", str(directory), "show", f"{REVISION}:{RESOURCE_PATH}/{filename}"])
        return {row.attrib["name"]: row.findtext("value") for row in ET.fromstring(content).findall("data")}

    canonical = resources("SH.resx")
    locales = {}
    for locale in LOCALES:
        localized = resources("SH.resx" if locale == "zh-Hans" else f"SH.{locale}.resx")
        locales[locale] = [localized.get(key) or canonical[key] for key in KEYS]
    return {"source": SOURCE, "revision": REVISION, "keys": KEYS, "locales": locales}


def generate(snapshot):
    lines = [
        "// Generated by scripts/generate-wiki-avatar-filter-labels.py from scripts/data/wiki-avatar-labels.json.",
        "// Vocabulary is limited to character Wiki filter choices.",
        "import { LocalePolicy } from '../model/LocalePolicy';",
        "",
        "export class WikiAvatarFilterWords {",
    ]
    for name in TERMS:
        lines.append(f"  readonly {name}: Record<string, string>;")
    lines.extend(["", "  constructor(qualities: Record<string, string>, weapons: Record<string, string>,",
                  "    elements: Record<string, string>, associations: Record<string, string>, bodies: Record<string, string>) {"])
    for name in TERMS:
        lines.append(f"    this.{name} = {name};")
    lines.extend(["  }", "}", "", "export class WikiAvatarFilterVocabulary {",
                  "  private static readonly WORDS: Record<string, WikiAvatarFilterWords> = {"])
    for locale in LOCALES:
        localized = dict(zip(snapshot["keys"], snapshot["locales"][locale]))
        lines.append(f"    '{locale}': new WikiAvatarFilterWords(")
        for index, terms in enumerate(TERMS.values()):
            names = {}
            for value, suffix in terms.items():
                key = "ModelIntrinsic" + suffix
                names[value] = localized[key]
            comma = "," if index + 1 < len(TERMS) else "),"
            lines.append("      " + json.dumps(names, ensure_ascii=False) + comma)
    lines.extend(["  };", "", "  static words(locale: string): WikiAvatarFilterWords {",
                  "    return WikiAvatarFilterVocabulary.WORDS[LocalePolicy.resourceLocale(locale)];",
                  "  }", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--windows", type=Path, help="Optional local Windows checkout to refresh or verify the pinned source snapshot")
    parser.add_argument("--check", action="store_true", help="Check the generated vocabulary without writing")
    args = parser.parse_args()
    if args.windows is None:
        snapshot = read_snapshot()
    else:
        snapshot = windows_snapshot(args.windows)
        if args.check:
            if snapshot != read_snapshot():
                raise SystemExit("Character Wiki label snapshot differs from the pinned Windows source")
        else:
            SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
            SNAPSHOT.write_text(json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    text = generate(snapshot)
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit("Character Wiki filter vocabulary differs from Windows resources")
    else:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"PASS: character Wiki filter labels for {len(LOCALES)} languages")


if __name__ == "__main__":
    main()
