// Rebuild the cultivation inventory catalog from Snap.Metadata (Chinese server data).
// Usage: node scripts/generate-inventory-material-reference.cjs <Genshin/CHS/Material.json>
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const input = process.argv[2];
if (!input) throw new Error('Pass the Snap.Metadata Genshin/CHS/Material.json path');
const bytes = fs.readFileSync(input);
const materials = JSON.parse(bytes.toString('utf8').replace(/^\uFEFF/, ''));
const combineBytes = fs.readFileSync(path.join(path.dirname(input), 'Combine.json'));
const combines = JSON.parse(combineBytes.toString('utf8').replace(/^\uFEFF/, ''));
// Material.IsInventoryItem, IntrinsicFrozen.MaterialTypeDescriptions and SHRegex,
// Snap.Hutao.Remastered 3b7475e. Mora and Masterless Stella Fortuna are explicit exceptions.
const types = new Set(['角色与武器培养素材', '角色经验素材', '角色突破素材', '角色天赋素材',
  '角色培养素材', '武器强化素材', '武器突破素材']);
const ids = materials.filter(m => m.Id !== 112001 && (m.Id === 202 || m.Id === 104300 ||
  types.has(m.TypeDescription) || /^[\u4e00-\u9fa5]+区域特产$/.test(m.TypeDescription || '')))
  .map(m => m.Id).sort((a, b) => a - b);
const lines = [];
for (let i = 0; i < ids.length; i += 12) lines.push('    ' + ids.slice(i, i + 12).join(', ') + ',');
const eligibleIds = new Set(ids);
const rankById = new Map(materials.map(material => [material.Id, material.RankLevel]));
const craftingPairs = combines.filter(recipe => recipe.RecipeType === 1 && recipe.Result.Count === 1 &&
  recipe.Materials.length === 1 && recipe.Materials[0].Count === 3 &&
  eligibleIds.has(recipe.Materials[0].Id) && eligibleIds.has(recipe.Result.Id) &&
  rankById.get(recipe.Materials[0].Id) < rankById.get(recipe.Result.Id))
  .map(recipe => [recipe.Materials[0].Id, recipe.Result.Id]);
craftingPairs.sort((left, right) => rankById.get(left[0]) - rankById.get(right[0]) || left[0] - right[0]);
const craftLines = [];
for (let i = 0; i < craftingPairs.length; i += 6) {
  craftLines.push('    ' + craftingPairs.slice(i, i + 6).map(pair => `[${pair.join(', ')}]`).join(', ') + ',');
}
const source = `/** Generated by scripts/generate-inventory-material-reference.cjs.
 * Windows Material.IsInventoryItem @ 3b7475e; Material.json SHA-256: ${crypto.createHash('sha256').update(bytes).digest('hex')}.
 * Combine.json SHA-256: ${crypto.createHash('sha256').update(combineBytes).digest('hex')}.
 */
export class InventoryMaterialReference {
  private static readonly ids: Set<number> = new Set<number>([
${lines.join('\n')}
  ]);

  /** Three of the first material synthesize one of the second, ordered from low to high rarity. */
  static readonly CRAFTING_PAIRS: number[][] = [
${craftLines.join('\n')}
  ];

  static includes(itemId: number): boolean { return InventoryMaterialReference.ids.has(itemId); }
  static itemIds(): number[] { return Array.from(InventoryMaterialReference.ids); }
}
`;
const output = path.resolve(__dirname, '../entry/src/main/ets/model/InventoryMaterialReference.ets');
fs.writeFileSync(output, source);
console.log(`Generated ${ids.length} cultivation material IDs`);
